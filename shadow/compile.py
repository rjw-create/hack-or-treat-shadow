"""Turn a validated plan into a readable, standalone Playwright script.

Usage: python -m shadow.compile runs/<id>/plan.json > automation.py
"""
import json
import sys

from shadow.steps import locator_code, validate_plan

HEADER = '''"""Generated by Shadow from one recorded demonstration."""
from playwright.sync_api import sync_playwright

with sync_playwright() as p:
    browser = p.chromium.launch(headless=False)
    page = browser.new_page()
'''

FOOTER = "    browser.close()\n"


def step_code(step):
    action = step["action"]
    if action == "goto":
        return f"page.goto({step['value']!r})"
    loc = locator_code(step["target"])
    if action == "click" and step["target"]["role"] in ("checkbox", "radio"):
        return f"{loc}.check()"
    if action == "click":
        return f"{loc}.click()"
    if action == "fill":
        return f"{loc}.fill({step['value']!r})"
    if action == "select":
        return f"{loc}.select_option(label={step['value']!r})"
    return f"{loc}.press({step['value']!r})"


def compile_plan(plan):
    validate_plan(plan)
    lines = [HEADER]
    for i, step in enumerate(plan["steps"], 1):
        # Intent text is model-written, so keep it on one line inside the comment.
        intent = " ".join(step["intent"].split())
        lines.append(f"    # {i}. {intent}\n    {step_code(step)}\n")
    lines.append(FOOTER)
    return "".join(lines)


if __name__ == "__main__":
    with open(sys.argv[1], encoding="utf-8") as f:
        sys.stdout.write(compile_plan(json.load(f)))
